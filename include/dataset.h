#pragma once

#include "vector_types.h"
#include <cstdint>
#include <string>
#include <vector>

// Dataset generation, (de)serialization, and the deterministic text-to-vector
// embedding used by the terminal demo. None of this depends on the index
// code -- the index only ever sees plain std::vector<float>.
namespace dataset {

struct ClusteredDataset {
    std::vector<Vector> database_vectors;
    std::vector<int> database_ids;   // 0 .. database_vectors.size()-1
    std::vector<Vector> query_vectors;
    std::size_t dimension = 0;
    std::size_t num_clusters = 0;
};

// Generates a synthetic clustered benchmark dataset:
//   1. `num_clusters` cluster centers are sampled uniformly from
//      [-1, 1]^dimension using a seeded RNG.
//   2. Each database/query vector is generated by picking a random cluster
//      center and adding Gaussian noise (std-dev `cluster_std`) to it.
// This gives the data real (if synthetic) cluster geometry, unlike vectors
// sampled uniformly at random, which is important because IVF's whole
// premise is that nearby vectors cluster together.
ClusteredDataset generate_clustered_dataset(std::size_t num_database_vectors,
                                             std::size_t num_queries, std::size_t dimension,
                                             std::size_t num_clusters, std::uint32_t seed,
                                             float cluster_std = 0.15f);

// --- Simple binary serialization (no external library) ---
// File layout: uint32 count, uint32 dimension, then count*dimension floats,
// all little-endian (matches the host in practice; this project targets a
// single machine's build+run, not cross-architecture portability).
void save_vectors_binary(const std::string& path, const std::vector<Vector>& vectors);
std::vector<Vector> load_vectors_binary(const std::string& path);

// --- Real text corpus demo ---
//
// generate_text_corpus() builds `num_texts` short synthetic support-style
// sentences across a fixed set of topics (password reset, billing, shipping,
// etc.), deterministically shuffled/varied from `seed`, and embeds each one
// with embed_text() below.
struct TextCorpus {
    std::vector<std::string> texts;
    std::vector<Vector> vectors;
    std::size_t dimension = 0;
};

TextCorpus generate_text_corpus(std::size_t num_texts, std::size_t dimension,
                                 std::uint32_t seed);

// Deterministically embeds a piece of text into a `dimension`-length vector
// using the hashing trick (a.k.a. feature hashing): the text is lowercased
// and split into words, each word is hashed to a dimension index and a
// random sign, and the resulting sparse contributions are summed then
// L2-normalized. This is a real, if simple, vector-space text
// representation (the same idea behind Vowpal Wabbit's hashing trick) --
// NOT a lookup table and NOT literal keyword substring matching. Two
// sentences that share more (hashed) vocabulary end up with higher cosine
// similarity. See README.md "Limitations" for why this is not a substitute
// for a trained neural embedding model, and how to swap one in.
Vector embed_text(const std::string& text, std::size_t dimension);

void save_text_corpus(const std::string& path, const TextCorpus& corpus);
TextCorpus load_text_corpus(const std::string& path, std::size_t dimension);

}  // namespace dataset
